/**
 * @file ai.analytics-center.tsx
 * @description Dedicated route component for AI Analytics Center.
 * Integrates AnalyticsCenterPage with the enterprise DashboardShell layout.
 */

import React, { useState, useCallback } from 'react';
import { useNavigate } from 'react-router-dom';
import { DashboardShell } from '@/shared/layout/DashboardShell';
import { DashboardSidebar } from '@/features/dashboard/components/DashboardSidebar';
import { AnalyticsCenterPage } from '@/features/analytics/pages/AnalyticsCenterPage';

export const AIAnalyticsCenterRoute: React.FC = () => {
  const navigate = useNavigate();
  const [sidebarCollapsed, setSidebarCollapsed] = useState(false);

  const toggleSidebar = useCallback(() => {
    setSidebarCollapsed((prev) => !prev);
  }, []);

  const handleTabChange = useCallback(
    (tabId: string) => {
      // If clicking another tab from sidebar, navigate back to HR dashboard with hash
      navigate(`/dashboard/hr-admin#${tabId}`);
    },
    [navigate]
  );

  return (
    <DashboardShell
      sidebar={
        <DashboardSidebar
          activeTab="analytics-center"
          onTabChange={handleTabChange}
          collapsed={sidebarCollapsed}
          onToggleCollapse={toggleSidebar}
        />
      }
      sidebarCollapsed={sidebarCollapsed}
      onSidebarToggle={toggleSidebar}
    >
      <AnalyticsCenterPage />
    </DashboardShell>
  );
};

export default AIAnalyticsCenterRoute;
