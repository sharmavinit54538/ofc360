import ExcelJS from 'exceljs';
import type { ReportDataset, XlsxSheetDef } from '../registry/types';

export interface XlsxExportOptions {
  filename: string;
  dataset: ReportDataset;
  title: string;
  generatedBy: string;
  sheets: XlsxSheetDef[];
  includeCharts?: boolean;
  chartImages?: Record<string, string>;
}

const CURRENCY_FORMAT = '#,##0.00';
const PERCENT_FORMAT = '0.0%';
const DATE_FORMAT = 'dd-mmm-yyyy';
const HEADER_STYLE = {
  font: { bold: true, color: { argb: 'FFFFFFFF' } },
  fill: { type: 'pattern' as const, pattern: 'solid' as const, fgColor: { argb: 'FF4F46E5' } },
  alignment: { horizontal: 'center' as const, vertical: 'middle' as const },
  border: {
    top: { style: 'thin' as const },
    bottom: { style: 'thin' as const },
    left: { style: 'thin' as const },
    right: { style: 'thin' as const },
  },
};

const TOTALS_STYLE = {
  font: { bold: true },
  fill: { type: 'pattern' as const, pattern: 'solid' as const, fgColor: { argb: 'FFF3F4F6' } },
  border: {
    top: { style: 'double' as const },
    bottom: { style: 'thin' as const },
  },
};

async function addSummarySheet(
  workbook: ExcelJS.Workbook,
  dataset: ReportDataset,
  title: string,
  generatedBy: string
): Promise<void> {
  const sheet = workbook.addWorksheet('Summary', {
    views: [{ state: 'frozen', ySplit: 1 }],
  });

  sheet.columns = [
    { header: 'Field', key: 'field', width: 30 },
    { header: 'Value', key: 'value', width: 60 },
  ];

  const rows: Array<{ field: string; value: any }> = [
    { field: 'Report Title', value: title },
    { field: 'Generated At', value: dataset.meta.generatedAt },
    { field: 'Generated By', value: generatedBy },
    { field: 'Currency', value: dataset.meta.currency },
    { field: '', value: '' },
    { field: 'Applied Filters', value: '' },
    ...Object.entries(dataset.meta.filters).map(([k, v]) => ({ field: k, value: v })),
    { field: '', value: '' },
    { field: 'KPI Metrics', value: '' },
    ...dataset.kpis.map((kpi) => ({
      field: kpi.label,
      value: kpi.unit ? `${kpi.value} ${kpi.unit}` : kpi.value,
    })),
    { field: '', value: '' },
    { field: 'Key Findings', value: '' },
  ];

  if (dataset.warnings.length > 0) {
    rows.push(
      { field: '', value: '' },
      { field: '⚠ Data Gaps / Warnings', value: '' },
      ...dataset.warnings.map((w) => ({ field: '', value: w }))
    );
  }

  const hasPersonalData = ['payroll-reports', 'statutory-compliance'].some((id) =>
    dataset.meta.reportId.includes(id)
  );

  if (hasPersonalData) {
    rows.push(
      { field: '', value: '' },
      { field: 'CONFIDENTIAL', value: 'This report contains personal data. Handle per data protection policy.' }
    );
  }

  sheet.addRows(rows);

  sheet.getRow(1).font = { bold: true };
  sheet.getRow(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF4F46E5' } };
  sheet.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' } };

  let currentRow = 1;
  rows.forEach((_, i) => {
    const row = sheet.getRow(currentRow + i);
    if (['Applied Filters', 'KPI Metrics', 'Key Findings', '⚠ Data Gaps / Warnings', 'CONFIDENTIAL'].includes(rows[i]?.field || '')) {
      row.font = { bold: true, color: { argb: 'FF1F2937' } };
      row.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFE5E7EB' } };
    }
  });

  sheet.getColumn(1).width = 30;
  sheet.getColumn(2).width = 80;
}

async function addDataSheet(
  workbook: ExcelJS.Workbook,
  dataset: ReportDataset,
  sheetDef: XlsxSheetDef
): Promise<void> {
  const sheet = workbook.addWorksheet(sheetDef.name, {
    views: [{ state: 'frozen', ySplit: 1 }],
  });

  const data = sheetDef.getData(dataset);
  const headers = sheetDef.headers || (data[0] as string[]);
  const rows = sheetDef.headers ? data : data.slice(1);

  sheet.columns = headers.map((h, i) => ({
    header: h,
    key: `col${i}`,
    width: sheetDef.columnWidths?.[i] || Math.max(12, Math.min(50, String(h).length + 4)),
  }));

  const headerRow = sheet.addRow(headers);
  headerRow.eachCell((cell) => {
    cell.style = HEADER_STYLE;
  });

  const dataRows = rows.map((row) => sheet.addRow(row));

  if (sheetDef.numberFormats) {
    dataRows.forEach((row) => {
      row.eachCell((cell, colNumber) => {
        const fmt = sheetDef.numberFormats![colNumber];
        if (fmt) cell.numFmt = fmt;
      });
    });
  }

  if (sheetDef.totalsRow && rows.length > 0) {
    const totalsRow = sheet.addRow([]);
    totalsRow.eachCell((cell, colNumber) => {
      if (colNumber === 1) {
        cell.value = 'TOTAL';
        cell.style = TOTALS_STYLE;
      } else if (sheetDef.numberFormats?.[colNumber]?.includes('#,##0')) {
        const colLetter = String.fromCharCode(64 + colNumber);
        const startRow = 2;
        const endRow = 1 + rows.length;
        cell.value = { formula: `SUM(${colLetter}${startRow}:${colLetter}${endRow})` };
        cell.numFmt = sheetDef.numberFormats[colNumber];
        cell.style = TOTALS_STYLE;
      } else {
        cell.style = TOTALS_STYLE;
      }
    });
  }

  sheet.autoFilter = {
    from: { row: 1, column: 1 },
    to: { row: 1, column: headers.length },
  };
}

async function addChartDataSheet(
  workbook: ExcelJS.Workbook,
  dataset: ReportDataset
): Promise<void> {
  const sheet = workbook.addWorksheet('Chart Data', {
    views: [{ state: 'frozen', ySplit: 1 }],
  });

  const seriesEntries = Object.entries(dataset.series);
  if (seriesEntries.length === 0) return;

  let col = 1;
  seriesEntries.forEach(([seriesKey, series]) => {
    const headerCell = sheet.getCell(1, col);
    headerCell.value = seriesKey;
    headerCell.style = HEADER_STYLE;

    if (series.categories) {
      sheet.getColumn(col).width = 20;
      series.categories.forEach((cat, i) => {
        sheet.getCell(i + 2, col).value = cat;
      });
      col++;
    }

    const dataCol = col;
    sheet.getCell(1, dataCol).value = series.name || 'Value';
    sheet.getCell(1, dataCol).style = HEADER_STYLE;
    series.data.forEach((val, i) => {
      sheet.getCell(i + 2, dataCol).value = val;
    });
    col++;
  });

  sheet.autoFilter = {
    from: { row: 1, column: 1 },
    to: { row: 1, column: col - 1 },
  };
}

async function addChartsSheet(
  workbook: ExcelJS.Workbook,
  dataset: ReportDataset,
  chartImages: Record<string, string>
): Promise<void> {
  const sheet = workbook.addWorksheet('Charts');
  const chartEntries = Object.entries(chartImages);
  if (chartEntries.length === 0) return;

  let row = 1;
  const colWidth = 80;

  for (const [chartId, base64] of chartEntries) {
    const chartDef = dataset.tables[chartId] || dataset.charts?.find?.((c) => c.id === chartId);
    const title = chartDef?.title || chartId;

    const titleCell = sheet.getCell(row, 1);
    titleCell.value = title;
    titleCell.font = { bold: true, size: 14 };
    sheet.getRow(row).height = 30;
    row += 2;

    try {
      const buffer = Buffer.from(base64, 'base64');
      const imageId = workbook.addImage({ buffer, extension: 'png' });
      workbook.addImage(imageId, {
        tl: { col: 0, row: row - 1 },
        ext: { width: colWidth, height: 400 },
      });
      row += 22;
    } catch {
      const errorCell = sheet.getCell(row, 1);
      errorCell.value = `[Chart image failed to embed: ${chartId}]`;
      errorCell.font = { color: { argb: 'FFEF4444' } };
      row += 2;
    }
  }

  sheet.getColumn(1).width = colWidth / 7;
}

export async function generateXlsx(options: XlsxExportOptions): Promise<Blob> {
  const { filename, dataset, title, generatedBy, sheets, includeCharts = false, chartImages = {} } = options;

  const workbook = new ExcelJS.Workbook();
  workbook.creator = generatedBy;
  workbook.created = new Date();
  workbook.modified = new Date();

  await addSummarySheet(workbook, dataset, title, generatedBy);

  for (const sheetDef of sheets) {
    await addDataSheet(workbook, dataset, sheetDef);
  }

  await addChartDataSheet(workbook, dataset);

  if (includeCharts && Object.keys(chartImages).length > 0) {
    await addChartsSheet(workbook, dataset, chartImages);
  }

  const buffer = await workbook.xlsx.writeBuffer();
  return new Blob([buffer], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
}

export function downloadXlsx(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename.endsWith('.xlsx') ? filename : `${filename}.xlsx`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function generateXlsxFilename(reportId: string, filters: Record<string, any>): string {
  const date = new Date().toISOString().split('T')[0];
  const slug = Object.entries(filters)
    .filter(([, v]) => v !== undefined && v !== null && v !== '')
    .map(([k, v]) => `${k}-${String(v).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`)
    .join('_')
    .slice(0, 100);
  return `ofc360_${reportId}_${date}${slug ? `_${slug}` : ''}.xlsx`;
}