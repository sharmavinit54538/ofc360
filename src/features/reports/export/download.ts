import { downloadCsv, generateCsvFilename } from './csv';
import { generateXlsx, downloadXlsx, generateXlsxFilename } from './xlsx';
import { captureAllCharts } from './chartImage';
import type { ReportDataset, ReportDefinition } from '../registry/types';
import { useToast } from '@/shared/ui/Toast';

export interface ExportOptions {
  report: ReportDefinition;
  dataset: ReportDataset;
  format: 'csv' | 'xlsx';
  tableName?: string;
  generatedBy?: string;
}

export async function exportReport(options: ExportOptions): Promise<void> {
  const { report, dataset, format, tableName, generatedBy = 'Current User' } = options;
  const toast = useToast.getState().toast;

  const exportBtn = document.querySelector(`[data-export-btn="${report.id}"]`) as HTMLButtonElement;
  if (exportBtn) {
    exportBtn.disabled = true;
    exportBtn.innerHTML = '<span class="animate-spin">⟳</span> Exporting...';
  }

  try {
    if (format === 'csv') {
      const table = tableName ? dataset.tables[tableName] : Object.values(dataset.tables)[0];
      if (!table) throw new Error('No table data to export');

      const rows = table.getRows(dataset);
      const headers = table.columns.map((c) => c.header);
      const data = rows.map((row) => table.columns.map((c) => row[c.key]));

      const filename = generateCsvFilename(report.id, dataset.meta.filters);
      downloadCsv({ filename, headers, rows: data });
      toast.success(`${report.title} exported as CSV`, 'Export Complete');
    } else {
      const sheets = report.xlsxSheets;
      const chartIds = report.charts.map((c) => c.id);
      const chartImages = await captureAllCharts(chartIds);

      const blob = await generateXlsx({
        filename: generateXlsxFilename(report.id, dataset.meta.filters),
        dataset,
        title: report.title,
        generatedBy,
        sheets,
        includeCharts: true,
        chartImages,
      });

      const filename = generateXlsxFilename(report.id, dataset.meta.filters);
      downloadXlsx(blob, filename);
      toast.success(`${report.title} exported as Excel`, 'Export Complete');
    }
  } catch (error) {
    console.error('Export failed:', error);
    toast.error('Failed to export report. Please try again.', 'Export Failed');
  } finally {
    if (exportBtn) {
      exportBtn.disabled = false;
      exportBtn.innerHTML = format === 'csv' ? 'CSV' : 'Excel';
    }
  }
}

export async function bulkExportReports(
  reports: ReportDefinition[],
  datasets: Map<string, ReportDataset>,
  dateRange: { startDate: string; endDate: string },
  generatedBy: string
): Promise<void> {
  const toast = useToast.getState().toast;
  const exceljs = await import('exceljs');
  const ExcelJS = exceljs.default;

  const workbook = new ExcelJS.Workbook();
  workbook.creator = generatedBy;
  workbook.created = new Date();

  const summarySheet = workbook.addWorksheet('Bulk Export Summary');
  summarySheet.columns = [
    { header: 'Field', key: 'field', width: 30 },
    { header: 'Value', key: 'value', width: 80 },
  ];

  summarySheet.addRows([
    { field: 'Export Type', value: 'Bulk Report Export' },
    { field: 'Generated At', value: new Date().toISOString() },
    { field: 'Generated By', value: generatedBy },
    { field: 'Date Range', value: `${dateRange.startDate} to ${dateRange.endDate}` },
    { field: 'Reports Included', value: reports.map((r) => r.title).join(', ') },
    { field: '', value: '' },
  ]);

  reports.forEach((report) => {
    const dataset = datasets.get(report.id);
    if (!dataset) return;

    summarySheet.addRow({ field: `--- ${report.title} ---`, value: '' });
    dataset.kpis.forEach((kpi) => {
      summarySheet.addRow({ field: kpi.label, value: kpi.unit ? `${kpi.value} ${kpi.unit}` : kpi.value });
    });
    summarySheet.addRow({ field: '', value: '' });
  });

  for (const report of reports) {
    const dataset = datasets.get(report.id);
    if (!dataset) continue;

    const mainTable = Object.values(dataset.tables)[0];
    if (!mainTable) continue;

    const sheet = workbook.addWorksheet(`Data - ${report.title.slice(0, 28)}`);
    sheet.views = [{ state: 'frozen', ySplit: 1 }];

    const headers = mainTable.columns.map((c) => c.header);
    const rows = mainTable.getRows(dataset);
    const data = rows.map((row) => mainTable.columns.map((c) => row[c.key]));

    sheet.columns = headers.map((h, i) => ({
      header: h,
      key: `col${i}`,
      width: Math.max(12, Math.min(50, String(h).length + 4)),
    }));

    const headerRow = sheet.addRow(headers);
    headerRow.eachCell((cell) => {
      cell.font = { bold: true, color: { argb: 'FFFFFFFF' } };
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF4F46E5' } };
      cell.alignment = { horizontal: 'center', vertical: 'middle' };
      cell.border = {
        top: { style: 'thin' },
        bottom: { style: 'thin' },
        left: { style: 'thin' },
        right: { style: 'thin' },
      };
    });

    data.forEach((row) => sheet.addRow(row));

    sheet.autoFilter = {
      from: { row: 1, column: 1 },
      to: { row: 1, column: headers.length },
    };
  }

  const buffer = await workbook.xlsx.writeBuffer();
  const blob = new Blob([buffer], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });

  const date = new Date().toISOString().split('T')[0];
  const filename = `ofc360_bulk-export_${date}.xlsx`;
  downloadXlsx(blob, filename);
  toast.success('Bulk export complete', 'Export Complete');
}