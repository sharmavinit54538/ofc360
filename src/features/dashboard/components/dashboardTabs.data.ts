export const getTabById = (id: string): DashboardTab => {
  const found = ALL_DASHBOARD_TABS.find((tab) => tab.id === id);
  return (
    found || {
      id,
      label: id.charAt(0).toUpperCase() + id.slice(1).replace(/-/g, ' '),
      category: 'core',
      categoryLabel: 'Core',
      icon: LayoutDashboard,
      description: 'Module view for ' + id,
      shortTagline: 'Executive HR Management',
    }
  );
};

export const getTabsByCategory = (category?: TabCategory | 'all'): DashboardTab[] => {
  if (!category || category === 'all') {
    return ALL_DASHBOARD_TABS;
  }
  return ALL_DASHBOARD_TABS.filter((tab) => tab.category === category);
};
